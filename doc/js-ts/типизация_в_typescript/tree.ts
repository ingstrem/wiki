type Shape = "circle" | "square";

/**
 * never — специальный тип в TypeScript, означающий «никогда не произойдёт»
 * или «недостижимый код»;
 *
 * Проверка на этапе компиляции:
 * если все возможные значения Shape уже обработаны в case,
 * то блок default недостижим — TypeScript разрешает такое присвоение (это безопасно);
 * если добавить новое значение в Shape, но не добавить соответствующий case,
 * TypeScript выдаст ошибку: «Тип ‘string’ не может быть присвоен типу ‘never’».
 */
function area(shape: Shape): number {
  switch (shape) {
    case "circle":
      return 1;
    case "square":
      return 2;
    default:
      const _: never = shape;
      return _;
  }
}

